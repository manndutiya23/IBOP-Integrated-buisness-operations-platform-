import express from "express";
import cors from "cors";
import dotenv from "dotenv";
import path from "path";
import { fileURLToPath } from "url";
import connectDB from "./config/db.js";
import productRoutes from "./routes/productRoutes.js";
import productCatalogueRoutes from "./routes/productCatalogueRoutes.js";
import manufacturerRoutes from "./routes/manufacturerRoutes.js";
import expenseRoutes from "./routes/expenseRoutes.js";
import saleRoutes from "./routes/saleRoutes.js";
import invoiceRoutes from "./routes/invoiceRoutes.js";
import purchaseRoutes from "./routes/purchaseRoutes.js";
import employeeRoutes from "./routes/employeeRoutes.js";
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
dotenv.config({ path: path.resolve(__dirname, ".env"), override: false });
dotenv.config({ path: path.resolve(__dirname, "..", ".env"), override: false });
const app = express();
const allowedOrigins = process.env.CORS_ORIGIN ? process.env.CORS_ORIGIN.split(",").map((origin) => origin.trim()).filter(Boolean) : ["http://localhost:5173", "http://localhost:3000"];
console.log("CORS allowed origins:", allowedOrigins);
await connectDB();
app.use(cors({ origin(origin, callback) { if (!origin || allowedOrigins.includes(origin)) return callback(null, true); return callback(new Error("Not allowed by CORS")); }, credentials: true }));
app.use(express.json({ limit: "5mb" }));
console.log("Mounting routes...");
app.use("/api/products", productRoutes);
app.use("/api/product-catalogue", productCatalogueRoutes);
app.use("/api/manufacturers", manufacturerRoutes);
app.use("/api/expenses", expenseRoutes);
app.use("/api/sales", saleRoutes);
app.use("/api/invoices", invoiceRoutes);
app.use("/api/purchases", purchaseRoutes);
app.use("/api/employees", employeeRoutes);
app.get("/", (req, res) => res.send("API is running..."));
app.use((req, res) => { console.log("404 - Path not found:", req.method, req.path); res.status(404).json({ error: "Not Found", path: req.path, method: req.method, message: "Route not found." }); });
const PORT = process.env.PORT || 5000;
app.listen(PORT, () => console.log(`Server running on port ${PORT}`));
